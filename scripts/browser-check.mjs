import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../src/server.js';
import { Store } from '../src/store.js';

// Optional browser verification: set PLAYWRIGHT_MODULE_ROOT to a directory
// containing Playwright's node_modules. No browser dependency is needed to run the app.
const require = createRequire(resolve(process.env.PLAYWRIGHT_MODULE_ROOT || '.', 'package.json'));
const { chromium } = require('playwright');
const store = new Store();
const app = createApp({ store, credentials: [{ token: 'browser-test-token', tenant: 'test-workspace', actor: 'tester', role: 'owner' }] });
await new Promise(resolve => app.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${app.address().port}`);
  await page.locator('#token').fill('browser-test-token');
  await page.getByRole('button', { name: 'Connect workspace' }).click();
  await page.waitForFunction(() => document.getElementById('notice').textContent === 'Workspace connected.');
  await page.locator('#key').fill('ai-summary');
  await page.locator('#rollout').fill('100');
  await page.locator('#enabled').check();
  await page.getByRole('button', { name: 'Save configuration' }).click();
  await page.waitForFunction(() => document.getElementById('notice').textContent.includes('version 1'));
  await page.locator('#user').fill('user-1');
  await page.getByRole('button', { name: 'Evaluate flag' }).click();
  await page.waitForFunction(() => document.getElementById('decision').textContent.includes('"matched"'));
  assert.equal(JSON.parse(await page.locator('#decision').textContent()).value, true);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Stop rollout' }).click();
  await page.waitForFunction(() => document.getElementById('notice').textContent.startsWith('Rollout stopped.'));
  assert.equal(store.get('test-workspace', 'development', 'ai-summary').enabled, false);
  await page.locator('#environment').selectOption('production');
  await page.waitForFunction(() => document.getElementById('notice').textContent === 'Switched to production.');
  assert.ok((await page.locator('#flags').textContent()).includes('No flags'));
  await page.locator('#environment').selectOption('development');
  await page.waitForFunction(() => document.getElementById('notice').textContent === 'Switched to development.');
  const output = resolve('data', 'verification'); mkdirSync(output, { recursive: true });
  await page.screenshot({ path: resolve(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: resolve(output, 'mobile.png'), fullPage: true });
  await page.goto(`http://127.0.0.1:${app.address().port}/agents`);
  await page.locator('#token').fill('browser-test-token');
  await page.getByRole('button',{name:'Connect workspace'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Workspace connected.');
  await page.locator('#kind').selectOption('judges');
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Library updated.');
  await page.locator('#key').fill('answer-judge');
  await page.getByRole('button',{name:'Save version'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Saved answer-judge, version 1.');
  await page.locator('#kind').selectOption('datasets');
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Library updated.');
  await page.locator('#key').fill('support-cases');
  await page.getByRole('button',{name:'Save version'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Saved support-cases, version 1.');
  await page.locator('#kind').selectOption('configs');
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Library updated.');
  await page.locator('#key').fill('support-agent');
  await page.locator('#advanced-editor > summary').click();
  const document=JSON.parse(await page.locator('#document').inputValue());
  document.judge='answer-judge';document.guard={minSamples:2,windowSeconds:60,minQuality:.8,action:'pause'};
  await page.locator('#document').fill(JSON.stringify(document,null,2));
  await page.locator('#model-0').fill('edited-model');
  assert.equal(JSON.parse(await page.locator('#document').inputValue()).variations[0].model,'edited-model');
  assert.equal(JSON.parse(await page.locator('#document').inputValue()).guard.minQuality,.8);
  await page.getByRole('button',{name:'Save version'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Saved support-agent, version 1.');
  await page.getByRole('tab',{name:'Test',exact:true}).click();
  for(let n=0;n<2;n++){
    await page.getByRole('button',{name:'Resolve configuration',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('notice').textContent==='Runtime configuration resolved.');
    await page.locator('#output').fill('wrong');
    await page.getByRole('button',{name:'Record outcome'}).click();
    await page.waitForFunction(()=>document.getElementById('notice').textContent==='Outcome recorded.'||document.getElementById('notice').textContent==='Safety action: pause.');
  }
  assert.ok((await page.locator('#alerts').textContent()).includes('pause'));
  await page.locator('#dataset').fill('support-cases');await page.locator('#judge').fill('answer-judge');
  await page.getByRole('button',{name:'Compare outputs'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Offline comparison saved.');
  assert.equal(JSON.parse(await page.locator('#benchmark-result').textContent()).summaries[0].meanScore,1);
  await page.getByRole('tab',{name:'Configure',exact:true}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('#restore-version').fill('1');
  await page.getByRole('button',{name:'Restore version'}).click();
  await page.waitForFunction(()=>document.getElementById('notice').textContent==='Previous resource restored as a new version.');
  await page.getByRole('tab',{name:'Configure',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab',{name:'Test',exact:true}).getAttribute('aria-selected'),'true');
  await page.keyboard.press('End');
  assert.equal(await page.getByRole('tab',{name:'Activity',exact:true}).getAttribute('aria-selected'),'true');
  await page.keyboard.press('Home');
  await page.setViewportSize({width:1440,height:1100});
  await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0);});
  await page.screenshot({path:resolve(output,'runtime-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:resolve(output,'runtime-mobile.png'),fullPage:true});
  assert.deepEqual(errors, []);
  console.log('Browser workflows passed: flags; runtime judge/dataset/config creation, resolution, online evaluation, automatic pause, offline comparison, restore; desktop/mobile overflow and console checks passed.');
} finally { if(browser) await browser.close(); await new Promise(resolve => app.close(resolve)); store.close(); }

